class Espacio {
  final String id;
  final String nombre;
  final String zona;
  final int capacidad;
  final String tipo;
  final String descripcion;
  final String imagen;
  final double precioPorHora;

  const Espacio({
    required this.id,
    required this.nombre,
    required this.zona,
    required this.capacidad,
    required this.tipo,
    required this.descripcion,
    required this.imagen,
    required this.precioPorHora,
  });
}
